// Quick helper to get department by name or ID
export function getDepartment(nameOrId: string): DepartmentData | undefined {
  const norm = nameOrId.toLowerCase().trim();
  return COLOMBIA_DEPARTMENTS.find(
    (d) => d.id === norm || d.name.toLowerCase() === norm
  );
}

// Get municipalities list for a department name
export function getMunicipalitiesForDepartment(deptName: string): string[] {
  const dept = COLOMBIA_DEPARTMENTS.find(
    (d) => d.name.toLowerCase().trim() === deptName.toLowerCase().trim()
  );
  return dept ? dept.municipalities : ['Ciudad Principal'];
}
